# while Loop depend on the condition of the loop it runs until the condition become false
# as the for loop has the fixed value but while don't have the fixed value
# when we don't know the fixed number of iteration then we use the while loop

# Syntax :
# while condition:
#    statements

# printing the value starting from 1 and it should be less than 5

num = 1

while num < 5:
    print(num)
    num += 1


