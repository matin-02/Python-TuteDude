# for Loop in python :-
# It is an iterator based loop which step through the item of a collection
# (List,tuples,sets,dict,str), and executes a block of code repeatedly
# for a number of times equal to the items or the element of that collection

# Syntax :-
#for i in sequence:
#    statement1
#    statement2
#   ...
#   statement n

per = [85.5,86.0,90.5,97.0]
for num in per:
    print(num)