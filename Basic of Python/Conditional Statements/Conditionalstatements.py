# Conditional statements in Python control the flow of your program by executing different blocks of
# code depending on whether a specified condition evaluates to True or False.
# Python relies on mandatory indentation (usually 4 spaces) instead of curly braces
# to define the scope of these code blocks.

# To build conditional rules, you use comparison operators:
# ==: Equal to
# !=: Not equal to
# > / <: Greater than / Less than
# >= / <=: Greater than or equal to / Less than or equal to
# You can combine multiple conditions using logical operators:
# and: Returns True if both conditions are true
# or: Returns True if at least one condition is true
# not: Reverses the boolean value of the condition